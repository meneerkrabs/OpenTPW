"""Golden rows of tp.exe's camera-loader yaw snap (0x42D03F, the tail of the loader 0x42CEC0) run in the x86 oracle at the thread's control word (docs/reverse/ORACLE.md, finding X48; SAVE-010).

Each row is `yaw bits > snapped bits | smoothed yaw bits`: a yaw (single) is written to gf_YRotation 0x790A38 with the rotation byte 0x78D912 set, the real tail of the loader runs (fprem through
0x67B24A, the compares against the single constants 0x6FDD6C, 0x6FDD90, 0x6FDD94, 0x6FDD98 and 0x6FDD68, the single-precision arithmetic at the control word 0x7F the Direct3D device leaves
the thread at), and the snapped target 0x790A38 and the smoothed yaw 0x7909E0 (which keeps the saved value) are read back. OpenTPW.Tests replays every row on ParkCameraMode.SnapToQuarterTurn.

Usage: python3 -I tools/ppc-analysis/oracle_x86/camera_snap_golden.py > source/OpenTPW.Tests/CameraSnapGolden.cs   (needs Unicorn and OPENTPW_TPW_EXE; --check FILE compares)
"""
from __future__ import annotations

import base64
import math
import struct
import sys
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from x86_harness import Image, Sandbox, executable_path, have_unicorn, seeded  # noqa: E402

TAIL, END = 0x42D03F, 0x42D0E3        # the snap and its three exits (each ends in pop esi, ret)
FMOD, FMOD_END = 0x67B24A, 0x67B272   # the CRT's fmod (fprem loop), entered through 0x6843E0
FMOD_GUARD = (0x6843E0, 0x684800)
ROTATION_BYTE, TARGET_YAW, SMOOTHED_YAW = 0x78D912, 0x790A38, 0x7909E0
CONTROL_WORD = 0x7F
SENTINEL = 0x78000000


def f32(value: float) -> float:
    return struct.unpack('<f', struct.pack('<f', value))[0]


def bits(value: float) -> int:
    return struct.unpack('<I', struct.pack('<f', value))[0]


def from_bits(value: int) -> float:
    return struct.unpack('<f', struct.pack('<I', value & 0xFFFFFFFF))[0]


def yaws() -> list[float]:
    rng = seeded('camera-snap-golden-v1')
    values = [0.0, -0.0, 1.0, -1.0, math.pi / 2, -math.pi / 2, math.pi, -math.pi, 2 * math.pi, -2 * math.pi]
    # around every odd multiple of pi/4 (where the rounding direction flips) and every multiple of pi/2
    for step in range(-12, 13):
        centre = step * math.pi / 4
        for delta in (0, 1e-6, -1e-6, 1e-4, -1e-4, 0.01, -0.01):
            values.append(centre + delta)
    values += [rng.uniform(-13, 13) for _ in range(300)]
    values += [rng.uniform(-1, 1) for _ in range(100)]
    return [f32(v) for v in values]


def render() -> str:
    path = executable_path('tpw')
    if path is None:
        raise SystemExit('needs OPENTPW_TPW_EXE')
    sandbox = Sandbox(Image.load(path), [(TAIL, END), (FMOD, FMOD_END), FMOD_GUARD], budget=20_000)
    lines = []
    for yaw in yaws():
        sandbox.reset()
        sandbox.set_fpcw(CONTROL_WORD)
        sandbox.write(ROTATION_BYTE, 'B', 1)
        sandbox.write(TARGET_YAW, 'f', yaw)
        sandbox.write(SMOOTHED_YAW, 'f', yaw)
        sandbox.call(TAIL, args=(SENTINEL,))
        lines.append(f'{bits(yaw):08x} > {sandbox.read(TARGET_YAW, "I"):08x} | {sandbox.read(SMOOTHED_YAW, "I"):08x}')
    packed = base64.b64encode(zlib.compress('\n'.join(lines).encode(), 9)).decode()
    out = ['// Generated by tools/ppc-analysis/oracle_x86/camera_snap_golden.py from tp.exe\'s camera-loader yaw snap 0x42D03F run in the x86 oracle at the control word 0x7F (docs/reverse/ORACLE.md, X48; SAVE-010).',
           '// Synthetic yaws, no original data. One row per line when unpacked, zlib-compressed and base64-coded: `yaw > snapped target | smoothed yaw`, each the 8 hex digits of a single.',
           'namespace OpenTPW.Tests;', '', 'internal static class CameraSnapGolden', '{',
           f'\t/// <summary>The oracle\'s {len(lines)} rows, packed.</summary>', '\tpublic const string Packed =']
    chunk = 120
    parts = [packed[i:i + chunk] for i in range(0, len(packed), chunk)]
    out += [f'\t\t"{part}"' + (' +' if i + 1 < len(parts) else ';') for i, part in enumerate(parts)]
    out += ['', f'\tpublic const int RowCount = {len(lines)};', '}', '']
    return '\n'.join(out)


def main() -> int:
    if not have_unicorn():
        print('needs Unicorn and OPENTPW_TPW_EXE', file=sys.stderr)
        return 2
    if len(sys.argv) == 3 and sys.argv[1] == '--check':
        if render() != Path(sys.argv[2]).read_text():
            print('CameraSnapGolden.cs differs from the oracle output', file=sys.stderr)
            return 1
        return 0
    print(render(), end='')
    return 0


if __name__ == '__main__':
    sys.exit(main())
