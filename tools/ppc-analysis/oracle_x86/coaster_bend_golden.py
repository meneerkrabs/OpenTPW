"""Golden rows of tp.exe's bend-car tables 0x438AB0 run in the x86 oracle at the thread's control word (docs/reverse/ORACLE.md, finding X43; COAST-034).

Each row is `bend | spacing low high rear-extent front-extent | direction | coordinate | samples > rear | yaw | pitch | elevation`: a synthetic sample list (flags, position, yaw and pitch of the
56-byte records), a car's extents, direction and coordinate go in; the rear count and the entries of the three tables the real routine writes come out. Every float is the 8 hex digits of a
single. OpenTPW.Tests replays every row on CoasterCarBend.Tables and compares the bits.

Usage: python3 -I tools/ppc-analysis/oracle_x86/coaster_bend_golden.py > source/OpenTPW.Tests/CoasterBendGolden.cs   (needs Unicorn and OPENTPW_TPW_EXE; --check FILE compares)
"""
from __future__ import annotations

import base64
import math
import sys
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from coaster_x87_oracle import CoasterOracle, bits, f32  # noqa: E402
from x86_harness import have_unicorn, seeded  # noqa: E402


def hexes(values) -> str:
    return ' '.join(f'{bits(v):08x}' for v in values)


def scenario(rng):
    count = rng.choice([6, 12, 25, 40, 70])
    x, y, z = rng.uniform(100, 600), rng.uniform(5, 40), rng.uniform(100, 600)
    heading = rng.uniform(-math.pi, math.pi) if rng.random() < 0.5 else rng.choice([math.pi - 0.1, -math.pi + 0.1])
    samples = []
    for index in range(count):
        heading += rng.uniform(-0.25, 0.25)
        climb = rng.uniform(-1.2, 1.2)
        step = (3 * math.sin(heading), climb, 3 * math.cos(heading))
        x, y, z = x + step[0], y + step[1], z + step[2]
        yaw = math.atan2(step[0], step[2])
        pitch = math.atan2(-step[1], math.hypot(step[0], step[2]))
        samples.append((8 if rng.random() < 0.2 else 0, (f32(x), f32(y), f32(z)), f32(yaw), f32(pitch)))
    spacing = f32(3.0 if rng.random() < 0.85 else rng.uniform(2, 4))
    low, high = f32(rng.uniform(0, 1)), f32(rng.uniform(0.5, 2))
    rear, front = f32(rng.uniform(0.5, 16)), f32(rng.uniform(0.5, 14))
    pick = rng.choice(['mid', 'mid', 'start', 'end', 'any'])
    last = count - 1
    coordinate = {'mid': rng.uniform(count * 0.3, count * 0.7), 'start': rng.uniform(0, 3), 'end': rng.uniform(max(0, last - 3), last), 'any': rng.uniform(0, last)}[pick]
    # the car points along the track there, more or less
    index = min(int(coordinate), count - 2)
    yaw_there = samples[index][2] + rng.uniform(-0.4, 0.4)
    pitch_there = samples[index][3] + rng.uniform(-0.3, 0.3)
    direction = (math.cos(pitch_there) * math.sin(yaw_there), -math.sin(pitch_there), math.cos(pitch_there) * math.cos(yaw_there))
    norm = math.sqrt(sum(v * v for v in direction))
    direction = tuple(f32(v / norm) for v in direction)
    return samples, spacing, low, high, rear, front, direction, f32(coordinate)


def rows(oracle: CoasterOracle, rng, count: int) -> list[str]:
    out = []
    while len(out) < count:
        samples, spacing, low, high, rear_extent, front_extent, direction, coordinate = scenario(rng)
        rear, tables = oracle.bend_tables(samples, spacing, low, high, rear_extent, front_extent, direction, coordinate)
        total = rear + 1 + int(front_extent / spacing) + 1
        if total > 128 or any(math.isnan(v) for table in tables for v in table[:total]):
            continue
        sample_text = ' '.join(f'{flags:08x} {hexes(list(position) + [yaw, pitch])}' for flags, position, yaw, pitch in samples)
        out.append(f'bend | {hexes([spacing, low, high, rear_extent, front_extent])} | {hexes(direction)} | {hexes([coordinate])} | {len(samples)} | {sample_text} > {rear} | '
                   + ' | '.join(hexes(table[:total]) for table in tables))
    return out


def render() -> str:
    oracle = CoasterOracle(budget=20_000_000)
    rng = seeded('coast-bend-golden-v1')
    lines = rows(oracle, rng, 120)
    packed = base64.b64encode(zlib.compress('\n'.join(lines).encode(), 9)).decode()
    out = ['// Generated by tools/ppc-analysis/oracle_x86/coaster_bend_golden.py from tp.exe\'s bend-car tables 0x438AB0 run in the x86 oracle at the control word 0x7F (docs/reverse/ORACLE.md, X43; COAST-034).',
           '// Synthetic sample lists and cars, no original data. One row per line when unpacked, zlib-compressed and base64-coded: `kind | inputs > outputs`, every float the 8 hex digits of a single.',
           'namespace OpenTPW.Tests;', '', 'internal static class CoasterBendGolden', '{',
           f'\t/// <summary>The oracle\'s {len(lines)} rows, packed.</summary>', '\tpublic const string Packed =']
    chunk = 120
    parts = [packed[i:i + chunk] for i in range(0, len(packed), chunk)]
    out += [f'\t\t"{part}"' + (' +' if i + 1 < len(parts) else ';') for i, part in enumerate(parts)]
    out += ['', f'\tpublic const int RowCount = {len(lines)};', '}', '']
    return '\n'.join(out)


def main() -> int:
    if not have_unicorn():
        print('needs Unicorn and OPENTPW_TPW_EXE', file=sys.stderr)
        return 2
    if len(sys.argv) == 3 and sys.argv[1] == '--check':
        if render() != Path(sys.argv[2]).read_text():
            print('CoasterBendGolden.cs differs from the oracle output', file=sys.stderr)
            return 1
        return 0
    print(render(), end='')
    return 0


if __name__ == '__main__':
    sys.exit(main())
