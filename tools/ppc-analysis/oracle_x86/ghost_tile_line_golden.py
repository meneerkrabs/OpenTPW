"""Golden cases of the tile line preview (docs/reverse/ORACLE.md, finding X51; BLUEPRINT-003): tp.exe's own tile walker 0x53AAC0 with the ghost tile routine 0x5370E0 and the chooser 0x539760 run on random lines.

Every case is a line of one to five tiles of the kart or water line tool or the fence tool (the Buy Land rectangle's edge) over a random synthetic map: map cell types, flags and owners, second-layer records of
track pieces, stations and posts, ground heights, class-3 owners, prices and money. The faces the ghost queues (the tile's origin cell, face code, texture, height step, direction byte and the two flags) and the
chooser's sticky words and cost after the last tile are recorded. OpenTPW.Tests replays every case on TileLineGhost.
Usage: python3 -I tools/ppc-analysis/oracle_x86/ghost_tile_line_golden.py > source/OpenTPW.Tests/GhostTileLineGolden.cs (needs Unicorn and OPENTPW_TPW_EXE).
"""
from __future__ import annotations

import base64
import json
import random
import sys
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from ghost_oracle import ANCHORS, GhostOracle, TOOL_OWNER  # noqa: E402

MAP = 128
CASES = 240


HEIGHTS=[0.0,4.0,9.5,12.0,25.0,31.5,40.0,-3.0,60.5,100.0]
def make(rng):
    mode=rng.choice((0xb,0x10,0x19,0x19))
    axis=rng.choice((0,1)); step=rng.choice((1,-1)); n=rng.choice((1,2,3,4,5))
    x0=rng.randint(30,60); y0=rng.randint(30,60)
    x1,y1=(x0+2*step*(n-1)+rng.choice((0,1)),y0) if axis==0 else (x0,y0+2*step*(n-1)+rng.choice((0,1)))
    if rng.random()<0.3: x1,y1=x0,y0
    cells={}; recs={}
    clean=rng.random()<0.5
    for x in range(min(x0,x1)-2,max(x0,x1)+4):
        for y in range(min(y0,y1)-2,max(y0,y1)+4):
            if clean: t=rng.choice([0]*10+[7,4,9]); fl=0
            else: t=rng.choice([0]*6+[1,3,4,7,9,10,0x1e,0x15]); fl=rng.choice([0]*10+[0x20,0x40])
            owner=rng.choice((ANCHORS[1],ANCHORS[2],0)) if t in (4,9,10) else 0
            cells[(x,y)]={'type':t,'flags':fl,'owner':owner}
            if rng.random()<0.2:
                k=rng.choice((0xb,0x10,0xd,0x12,0x19,7,0xb,0x10))
                recs[(x,y)]=(k,rng.choice([0,1,4,0x10,0x40,5,0x14,0x11,0x44,0x15]),0,rng.choice((0,1,4,0x10,0x40)),rng.choice([0,0,0,1,2,0x10,0x11]),rng.choice((TOOL_OWNER,TOOL_OWNER,TOOL_OWNER+1)))
    anchors={a:rng.randint(0,5) for a in (1,2,3) if rng.random()<0.7}
    heights={k:rng.choice(HEIGHTS) for k in cells}
    G={0x818698:TOOL_OWNER,0x818C10:3,0x818688:rng.choice((0,1)),0x81AEBC:rng.choice((0,10,50)),0x81B43C:rng.choice((0,20,60)),0x8186D4:0,0x8186D0:0,
       0x816D4C:0,0x816D60:0,0x7639F0:0,0x7639F4:0,0x7639F8:0,0x7639FC:0,0x81AF4C:0,0x820AC8:0,0x820AD0:0,0x816D50:0,0x816D58:0,0x816D54:0,0x816D5C:0}
    gates=(rng.choice((x0,x0+2,0)),rng.choice((y0,y0+2,0)),rng.choice((x0,x1,0)),rng.choice((y0,y1,0)))
    G.update({0x7639F0:gates[0],0x7639F4:gates[1],0x7639F8:gates[2],0x7639FC:gates[3]})
    pr=rng.choice((0,0,1))
    G[0x816D50]=pr
    return {'preset_refuse':pr,'gates':gates,'mode':mode,'start':(x0,y0),'end':(x1,y1),'cells':cells,'records':recs,'anchors':anchors,'ground':(lambda hh: (lambda x,y: hh.get((x,y),0.0)))(heights),
            'heights':heights,'price':(G[0x81AEBC],G[0x81B43C]),'bank':rng.choice((None,None,0,30,1000)),'hover_is_start':bool(G[0x818688]),'G':G}


def render() -> str:
    oracle = GhostOracle()
    oracle.start([], [])
    rng = random.Random('ghost-tile-line-x50')
    lines = []
    for _ in range(CASES):
        case = make(rng)
        result = oracle.tile_line(case)
        lines.append(json.dumps({
            'mode': case['mode'], 'start': list(case['start']), 'end': list(case['end']), 'hoverIsStart': case['hover_is_start'],
            'price': list(case['price']), 'bank': case['bank'], 'gates': list(case['gates']), 'presetRefuse': case['preset_refuse'],
            'cells': [[x, y, c['type'], c['flags'], c['owner']] for (x, y), c in sorted(case['cells'].items())],
            'records': [[x, y, *r] for (x, y), r in sorted(case['records'].items())],
            'anchors': {str(ANCHORS[a]): p for a, p in sorted(case['anchors'].items())},
            'heights': [[x, y, h] for (x, y), h in sorted(case['heights'].items())],
            'faces': [list(f) for f in result['faces']], 'latches': result['latches'], 'cost': result['cost']}, separators=(',', ':')))
    packed = base64.b64encode(zlib.compress('\n'.join(lines).encode(), 9)).decode()
    out = ['// Generated by tools/ppc-analysis/oracle_x86/ghost_tile_line_golden.py from tp.exe\'s own tile walker 0x53AAC0 with the ghost tile routine 0x5370E0 run in the x86 oracle (docs/reverse/ORACLE.md, X51).',
           '// Synthetic maps, no original data. One JSON object per line when unpacked: the tool state, the line, the cells, records and heights it reads, and the faces the ghost queued (origin x, origin y,',
           '// face code, texture, height step, direction byte, flag, tile flag) with the chooser\'s words 0x816D50, 0x816D58, 0x816D54, 0x816D5C, 0x816D4C, 0x816D60, 0x816D48 and the cost 0x81AF4C after it.',
           'namespace OpenTPW.Tests;', '', 'internal static class GhostTileLineGolden', '{',
           f'\t/// <summary>The oracle\'s {len(lines)} cases, packed.</summary>', '\tpublic const string Packed =']
    chunk = 120
    parts = [packed[i:i + chunk] for i in range(0, len(packed), chunk)]
    out += [f'\t\t"{part}"' + (' +' if i + 1 < len(parts) else ';') for i, part in enumerate(parts)]
    out += ['', f'\tpublic const int CaseCount = {len(lines)};', '}', '']
    return '\n'.join(out)


def main() -> int:
    if len(sys.argv) == 3 and sys.argv[1] == '--check':
        if render() != Path(sys.argv[2]).read_text():
            print('GhostTileLineGolden.cs differs from the oracle output', file=sys.stderr)
            return 1
        return 0
    print(render(), end='')
    return 0


if __name__ == '__main__':
    sys.exit(main())
