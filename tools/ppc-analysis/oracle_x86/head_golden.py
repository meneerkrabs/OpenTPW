"""Golden cases of the head placement (docs/reverse/ORACLE.md; HEADS-004): tp.exe's routine 0x0044B510 on synthetic head nodes and cameras.

Every case is a node world matrix and a camera matrix (16 float bit patterns each, row major, translation in the fourth row), the node's flag word, and what the routine sets on the head's sprite: the
frame register 0xD (-1 for a hidden head), the roll register 9 and the scale register 8 (float bit patterns) and the position it passes to 0x475480. `head_oracle.HeadOracle` runs the executable's
routine in the Unicorn sandbox; OpenTPW.Tests replays every case on `OriginalHeadMath` and must reproduce them bit for bit.

Usage: python3 -I tools/ppc-analysis/oracle_x86/head_golden.py > source/OpenTPW.Tests/HeadPlacementGolden.cs   (needs Unicorn and OPENTPW_TPW_EXE)
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from head_oracle import HeadOracle, bits  # noqa: E402
from x86_harness import seeded  # noqa: E402


def rotation(yaw, pitch, roll):
    cy, sy, cp, sp, cr, sr = math.cos(yaw), math.sin(yaw), math.cos(pitch), math.sin(pitch), math.cos(roll), math.sin(roll)
    ry = [[cy, 0, -sy], [0, 1, 0], [sy, 0, cy]]
    rp = [[1, 0, 0], [0, cp, sp], [0, -sp, cp]]
    rr = [[cr, sr, 0], [-sr, cr, 0], [0, 0, 1]]
    def mul(a, b):
        return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
    return mul(mul(rr, rp), ry)


def matrix(rotation_rows, scale, position):
    rows = []
    for i in range(3):
        rows.append([rotation_rows[i][j] * scale[i] for j in range(3)] + [0.0])
    rows.append(list(position) + [1.0])
    return rows


def normalise(v):
    length = math.sqrt(sum(c * c for c in v))
    return [c / length for c in v]


def cross(a, b):
    return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]


def camera_looking(eye, target, roll):
    front = normalise([target[i] - eye[i] for i in range(3)])
    right = normalise(cross([0, 1, 0], front)) if abs(front[1]) < 0.999 else [1, 0, 0]
    up = cross(front, right)
    c, s = math.cos(roll), math.sin(roll)
    right2 = [right[i] * c + up[i] * s for i in range(3)]
    up2 = [-right[i] * s + up[i] * c for i in range(3)]
    return [right2 + [0.0], up2 + [0.0], front + [0.0], list(eye) + [1.0]]


def flat(rows):
    return [bits(v) for row in rows for v in row]


def cases(count=700):
    rng = seeded('head-placement')
    quarter = math.pi / 4
    sixth = math.pi / 6
    for index in range(count):
        kind = index % 7
        if kind == 0:   # axis-aligned and eighth-turn nodes with a camera on an axis: the ties of the frame search
            yaw = rng.choice([0, 1, 2, 3, 4, 5, 6, 7]) * quarter
            pitch = rng.choice([0, 1, -1, 3, 6]) * sixth
            roll = rng.choice([0, 1, 2, 4]) * quarter
        elif kind == 1:
            yaw, pitch, roll = rng.uniform(-math.pi, math.pi), rng.uniform(-1.5, 1.5), rng.uniform(-math.pi, math.pi)
        else:
            yaw, pitch, roll = rng.uniform(-math.pi, math.pi), rng.uniform(-math.pi / 2, math.pi / 2), rng.uniform(-math.pi, math.pi)
        scale_kind = rng.random()
        if scale_kind < 0.4:
            scale = [1.0, 1.0, 1.0]
        elif scale_kind < 0.7:
            s = rng.choice([0.5, 2.0, 0.25, rng.uniform(0.3, 3.0)])
            scale = [s, s, s]
        else:
            scale = [rng.uniform(0.3, 2.5) for _ in range(3)]
        position = [rng.uniform(-300, 300), rng.uniform(0, 40), rng.uniform(-300, 300)]
        node = matrix(rotation(yaw, pitch, roll), scale, position)
        distance = rng.uniform(1.0, 400.0)
        direction = normalise([rng.uniform(-1, 1), rng.uniform(-0.2, 1), rng.uniform(-1, 1)])
        eye = [position[i] + direction[i] * distance for i in range(3)]
        if kind == 0:
            eye = [position[0], position[1] + distance, position[2]] if index % 14 == 0 else [position[0] + distance, position[1], position[2]]
        camera = camera_looking(eye, position, rng.choice([0.0, rng.uniform(-math.pi, math.pi)]))
        flags = rng.choice([0, 0, 0, 0x400, 0x400, 0x8000, 0x8400, 0x1234])
        if index % 53 == 0:   # a degenerate node: the inverse hits the pivot guard
            node[1] = [0.0, 0.0, 0.0, 0.0]
        yield node, camera, flags


def main():
    oracle = HeadOracle()
    out = []
    out.append('// Generated by tools/ppc-analysis/oracle_x86/head_golden.py from tp.exe 0x0044B510 run in the Unicorn sandbox (synthetic nodes and cameras, no original data). Do not edit.')
    out.append('namespace OpenTPW.Tests;')
    out.append('')
    out.append('internal static class HeadPlacementGolden')
    out.append('{')
    out.append('\tinternal readonly record struct Case( uint[] Node, uint[] Camera, uint Flags, int Frame, uint Roll, uint Scale, uint[] Position );')
    out.append(f'\tinternal static readonly uint TableHash = 0x{oracle_table_hash(oracle):08X};')
    out.append('\tinternal static readonly Case[] Cases =')
    out.append('\t{')
    for node, camera, flags in cases():
        frame, roll, scale, position = oracle.head(flat(node), flat(camera), flags)
        def arr(values):
            return 'new uint[] { ' + ', '.join(f'0x{v:08X}' for v in values) + ' }'
        out.append(f'\t\tnew( {arr(flat(node))}, {arr(flat(camera))}, 0x{flags:X}, {frame if frame is not None else -2}, 0x{(roll or 0):08X}, 0x{(scale or 0):08X}, {arr(position or (0, 0, 0))} ),')
    out.append('\t};')
    out.append('}')
    print('\n'.join(out))


def oracle_table_hash(oracle):
    value = 0x811C9DC5   # FNV-1a over the 4096 table entries' bytes
    for byte in oracle.table_bytes[0xC:0xC + 4 * 4096]:   # the entries start at 0x7B0968
        value = ((value ^ byte) * 0x01000193) & 0xFFFFFFFF
    return value


if __name__ == '__main__':
    main()
