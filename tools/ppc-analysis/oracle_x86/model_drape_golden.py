"""Golden cases of the model drape of tp.exe's 0x469A80 (docs/PATHS.md, "Queue models").

The cases come from `x86_targets.drape_case` (a seeded generator, not original data); `model_drape_reading.drape` reproduces the original's vertex heights for them (the x86 oracle target
`tpw-exe-model-drape` compares both on 400 and more cases, node space, bit for bit). OpenTPW.Tests runs the C# port (`ModelDrape`, `LandscapeSampler.SampleDrape`) on the same cases without any
game data and checks the vertex in the grid's frame, bit for bit.

Usage: python3 -I model_drape_golden.py > source/OpenTPW.Tests/ModelDrapeGolden.cs
Needs no Unicorn when x86_targets can be imported without it (the harness imports it lazily): the reading is pinned against the executable by test_x86_oracle.py when the identified tp.exe is available.
"""
from __future__ import annotations

import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import model_drape_reading as reading  # noqa: E402
import x86_targets  # noqa: E402


def literal(value: float) -> str:
    text = '%.9g' % value
    if 'e' not in text and '.' not in text:
        text += '.0'
    return text + 'f'


def flatten(node: dict, parent: int, out: list) -> None:
    index = len(out)
    out.append((parent, node))
    for child in node['children']:
        flatten(child, index, out)


def main() -> int:
    rng = random.Random(829)
    cases = [x86_targets.drape_case(rng, index, small=True) for index in range(64)]
    out = ['// Generated by tools/ppc-analysis/oracle_x86/model_drape_golden.py from the reading of tp.exe 0x469940 / 0x469A80 that the x86 oracle pins (docs/PATHS.md, docs/reverse/ORACLE.md X33).',
           '// Synthetic landscapes and models, not original data: each case is a landscape (corner heights, the cell words\' diagonal bit), the instance height and a tree of nodes (the root carries the placement);',
           '// World holds, for the nodes the drape moves, the grid-frame position of every vertex after the drape as float bits.',
           'namespace OpenTPW.Tests;', '', 'internal static class ModelDrapeGolden', '{',
           '\tpublic readonly record struct Node( int Parent, int Flags, float[] Matrix, float[][] Vertices, uint[][] World );',
           '\tpublic readonly record struct Case( int CellsX, int CellsZ, float SizeX, float SizeZ, float[] Heights, bool[] Anti, float BaseHeight, Node[] Nodes );', '',
           '\tpublic static readonly Case[] Cases =', '\t[']
    for case in cases:
        land = case['landscape']
        world = reading.drape(case)['world']
        flat: list = []
        flatten(case['tree'], -1, flat)
        anti = ', '.join('true' if land['flags'][4 * cell] & 4 else 'false' for cell in range(land['cells'][0] * land['cells'][1]))
        nodes = []
        for (parent, node), moved in zip(flat, world):
            vertices = ', '.join('[%s]' % ', '.join(literal(c) for c in v) for v in node['vertices'])
            bits = ', '.join('[%s]' % ', '.join('0x%08X' % c for c in v) for v in moved)
            nodes.append('new( %d, 0x%X, [%s], [%s], [%s] )' % (parent, node['flags'], ', '.join(literal(v) for v in node['matrix']), vertices, bits))
        out.append('\t\tnew( %d, %d, %s, %s, [%s], [%s], %s,\n\t\t\t[%s] ),' % (land['cells'][0], land['cells'][1], literal(land['cell'][0]), literal(land['cell'][1]),
                                                                          ', '.join(literal(h) for h in land['heights']), anti, literal(case['base_height']),
                                                                          ',\n\t\t\t\t'.join(nodes)))
    out += ['\t];', '}', '']
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
