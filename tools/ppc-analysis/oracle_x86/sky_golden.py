"""Golden numbers of the sky draw 0x5863C0 (docs/reverse/ORACLE.md 7.40, finding X78): the records tp.exe's own draw makes, run in the x86 oracle, for the normal render flags and the globe's 0x2000000.

Only numbers: the record states, the triangle index lists, the grid's positions in the original's axes, every texture coordinate of every layer and of the cylinder under fixed scroll offsets, and the alpha byte of each record's
colours. No original data enters (the constructor's rand() colours are not written, the stub's seed is fixed). OpenTPW.Tests replays them on Sky.BuildVertices (SkyGoldenTests).

Usage: python3 -I tools/ppc-analysis/oracle_x86/sky_golden.py > source/OpenTPW.Tests/SkyGolden.cs   (needs Unicorn and OPENTPW_TPW_EXE)
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from sky_oracle import GLOBE, SkyOracle  # noqa: E402

GRID = 256
CYLINDER = 72
# the scroll words written to the sky object (v at +0, u at +8 of each layer's triple): the layers' offsets come out as these
SCROLL = [(0.1 * (layer + 1), 0.05 * (layer + 1)) for layer in range(4)]


def f32(value: float) -> str:
    text = format(struct.unpack('<f', struct.pack('<f', value))[0], '.9g')
    if text in ('-0', '0'):
        return '0f'
    return text + 'f'


def numbers(values) -> str:
    return ', '.join(f32(value) for value in values)


def case(oracle: SkyOracle, name: str, flags: int):
    sky, records = oracle.run(flags, scroll=SCROLL)
    layers = oracle.layer_count
    mirrored = 2 if flags & GLOBE else 1
    assert len(records) == layers * mirrored + 1, (name, len(records))
    cloud = [oracle.vertices(record, GRID) for record in records[:-1]]
    cylinder = oracle.vertices(records[-1], CYLINDER)
    for record in records[:-1]:
        assert record['indices'] == records[0]['indices']
    for layer in range(layers):
        for copy in range(1, mirrored):
            first, second = cloud[layer], cloud[copy * layers + layer]
            assert [(v[3], v[4], v[5]) for v in first] == [(v[3], v[4], v[5]) for v in second], 'mirrored layers keep colour and texture coordinates'
            assert all(abs(a[0] + b[0]) < 0.01 and abs(a[1] + b[1]) < 0.01 and a[2] == b[2] for a, b in zip(first, second)), 'mirror: x and the height negated, z kept'
    offsets = []
    signs = [(-1, 1), (-1, -1), (1, -1), (1, 1)]
    for layer in range(layers):
        u, v = cloud[layer][0][4], cloud[layer][0][5]
        offsets.append((signs[layer % 4][0] * u, signs[layer % 4][1] * v))
    lines = [f'\t\tnew( "{name}", {"true" if flags & GLOBE else "false"}, {layers},',
             f'\t\t\tStates: [{", ".join(hex(record["state"]) for record in records)}],',
             f'\t\t\tOffsetU: [{numbers(o[0] for o in offsets)}], OffsetV: [{numbers(o[1] for o in offsets)}],',
             f'\t\t\tAlphas: [{", ".join(str(record_vertices[0][3] >> 24) for record_vertices in cloud)}],',
             f'\t\t\tCloudPositions: [{numbers(c for v in cloud[0] for c in v[:3])}],',
             f'\t\t\tMirroredPositions: [{numbers(c for v in cloud[layers] for c in v[:3]) if mirrored > 1 else ""}],',
             f'\t\t\tCloudUv: [{numbers(c for layer in range(layers) for v in cloud[layer] for c in v[4:6])}],',
             f'\t\t\tCylinderPositions: [{numbers(c for v in cylinder for c in v[:3])}],',
             f'\t\t\tCylinderUv: [{numbers(c for v in cylinder for c in v[4:6])}] ),']
    return lines, records[0]['indices'], records[-1]['indices']


def main() -> None:
    oracle = SkyOracle()
    out = ['// <auto-generated> by tools/ppc-analysis/oracle_x86/sky_golden.py (finding X78, docs/reverse/ORACLE.md 7.40): numbers of the sky draw 0x5863C0 run in the x86 oracle. Do not edit.',
           'namespace OpenTPW.Tests;', '',
           '/// <summary>The records of tp.exe\'s sky draw for the normal render flags and the globe\'s 0x2000000 (positions in the original\'s axes, texture coordinates as the draw writes them).</summary>',
           'internal static class SkyGolden', '{',
           '\tinternal sealed record Case( string Name, bool Globe, int Layers, uint[] States, float[] OffsetU, float[] OffsetV, int[] Alphas, float[] CloudPositions,',
           '\t\tfloat[] MirroredPositions, float[] CloudUv, float[] CylinderPositions, float[] CylinderUv );', '']
    cloud_indices, cylinder_indices = None, None
    body = []
    for name, flags in (('normal', 0), ('globe', GLOBE)):
        lines, cloud_i, cyl_i = case(oracle, name, flags)
        body += lines
        if cloud_indices is not None:
            assert cloud_indices == cloud_i and cylinder_indices == cyl_i
        cloud_indices, cylinder_indices = cloud_i, cyl_i
    out.append(f'\tinternal static readonly int[] CloudIndices = [{", ".join(map(str, cloud_indices))}];')
    out.append(f'\tinternal static readonly int[] CylinderIndices = [{", ".join(map(str, cylinder_indices))}];')
    out.append('')
    out.append('\tinternal static readonly Case[] Cases = [')
    out += body
    out.append('\t];')
    out.append('}')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
