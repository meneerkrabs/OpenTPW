"""Golden cases of a placed kart or water station (docs/reverse/ORACLE.md, finding X38; ECON-026): tp.exe's own placement routines on synthetic maps.

Every case is a 128 x 128 map built here (all cells owned, no original data) and one placement as the click handler runs it: the commit 0x528A70 of the ride's footprint, the station line (two tiles and their
extension cells), the exit and entry tiles; the add-on cases then commit a 2 x 2 add-on footprint ('++' / '++') over the exit tile. `station_oracle.StationOracle` runs the executable's routines in the Unicorn
sandbox; this script records, per case, every cell near the placement that holds something (first-layer type, flags, links, queue link; second-layer record type, arms, flow link and parent) relative to the
placement's anchor, and the net worth 0x4C7DB0 of the whole map. OpenTPW.Tests replays every case on the level's placement (TrackStationFootprintOracleTests) and must reproduce them.

Usage: python3 -I tools/ppc-analysis/oracle_x86/station_golden.py > source/OpenTPW.Tests/StationFootprintGolden.cs   (needs Unicorn and OPENTPW_TPW_EXE; `--check FILE` compares instead of printing)
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from station_oracle import StationOracle  # noqa: E402

# the shipped kart stations' shape has three text rows, the water rides' four; the last row is the entrance row
# (the oracle's table lists the entrance row first; the golden file gives the text order of Info.Shape, the entrance row last)
KART = ['*2N*', '****', '****']
WATER = ['*2N*', '****', '****', '****']
ADD_ON = ['++', '++']
CLICK = (60, 60)

CASES = [(name, track_type, shape, rotation, False)
         for name, track_type, shape in (('kart', 1, KART), ('water', 2, WATER))
         for rotation in (0, 90, 180, 270)]
CASES += [('kart with an add-on on its exit tile', 1, KART, 0, True), ('water with an add-on on its exit tile', 2, WATER, 270, True)]


def run(spec, oracle):
    name, track_type, shape, rotation, add_on = spec
    oracle.start([], [])
    oracle.own_all()
    oracle.build_type(shape)
    oracle.place_station(CLICK[0], CLICK[1], rotation, track_type)
    anchor = oracle.anchor()
    at = (0, 0)
    if add_on:
        exit_x, exit_y = oracle.exit
        # the click that puts the 2 x 2 add-on's origin on the exit tile's origin cell
        oracle.place_add_on(exit_x + 1, exit_y + 1, 0, ADD_ON)
        at = (exit_x - anchor[0], exit_y - anchor[1])
    return {'cells': oracle.cells_around(anchor), 'worth': oracle.net_worth(), 'add_on_at': at}


def literal(spec, result):
    name, track_type, shape, rotation, add_on = spec
    # Info.Shape's text order: the entrance row is the last row (the oracle's table lists it first)
    shape_text = ', '.join(f'"{row}"' for row in reversed(shape))
    cells = ', '.join('new( ' + ', '.join(str(value) for value in cell) + ' )' for cell in result['cells'])
    add_on_text = f'({result["add_on_at"][0]}, {result["add_on_at"][1]})' if add_on else 'null'
    return (f'\t\tnew( "{name}", {track_type}, {rotation}, [{shape_text}], {add_on_text}, {result["worth"]},\n\t\t\t[{cells}] ),')


def render() -> str:
    oracle = StationOracle()
    out = ['// Generated by tools/ppc-analysis/oracle_x86/station_golden.py from tp.exe\'s own placement routines run in the x86 oracle (docs/reverse/ORACLE.md, X38).',
           '// Synthetic 128 x 128 maps with every cell owned, no original data: the cells near a placed kart or water station (and an add-on over its exit tile) and the net worth 0x4C7DB0 of the map.',
           'namespace OpenTPW.Tests;', '', 'internal static class StationFootprintGolden',
           '{',
           '\t/// <summary>One cell relative to the placement\'s anchor: the first-layer type, flag word, link byte and queue link, then the second-layer record\'s type, arms and flow link and (type 12) its parent\'s offset.</summary>',
           '\tinternal readonly record struct Cell( int Dx, int Dy, int Type, int Flags, int Links, int Queue, int Record, int Arms, int Flow, int ParentDx, int ParentDy );', '',
           '\t/// <summary>A case: the ride (1 kart, 2 water), its rotation and shape rows, the add-on\'s origin relative to the anchor (or null), the net worth of the whole map and the cells.</summary>',
           '\tinternal sealed record Case( string Name, int TrackType, int Rotation, string[] Shape, (int Dx, int Dy)? AddOnAt, int NetWorth, Cell[] Cells );', '',
           '\tpublic static readonly Case[] Cases =', '\t[']
    for spec in CASES:
        out.append(literal(spec, run(spec, oracle)))
    out += ['\t];', '}', '']
    return '\n'.join(out)


def main() -> int:
    if len(sys.argv) == 3 and sys.argv[1] == '--check':
        expected = Path(sys.argv[2]).read_text()
        if render() != expected:
            print('StationFootprintGolden.cs differs from the oracle output', file=sys.stderr)
            return 1
        return 0
    print(render(), end='')
    return 0


if __name__ == '__main__':
    sys.exit(main())
