"""Golden sequences of the visible-cell cache of tp.exe's 0x572440 (docs/LND.md, "The cache").

The frames come from `terrain_cache.random_sequences` (a seeded generator, not original data); `terrain_cache.Cache` reproduces the original's slots, builds, ring and key table for them (the x86 oracle
target `terrain_cache` compares both on 300 and more runs). OpenTPW.Tests replays the frames through `ProceduralTextureCache.Resolve` without any game data.

Usage: python3 -I terrain_cache_golden.py > source/OpenTPW.Tests/ProceduralTextureCacheGolden.cs
"""
from __future__ import annotations

import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import terrain_cache as tc  # noqa: E402


def ints(values) -> str:
    return '[' + ', '.join(str(int(v)) for v in values) + ']'


def main() -> int:
    runs = tc.random_sequences(random.Random(829), 48)
    out = ['// Generated by tools/ppc-analysis/oracle_x86/terrain_cache_golden.py from the reading of tp.exe 0x572440 that the x86 oracle pins (docs/LND.md).',
           '// Synthetic frames of cell keys, not original data: the slots each key takes, the cells built (indices into the frame), the ring from the head after the frame.',
           'namespace OpenTPW.Tests;', '', 'internal static class ProceduralTextureCacheGolden', '{',
           '\tpublic readonly record struct Frame( int[] Keys, bool[] Dirty, int[] Slots, int[] Built, int[] Ring );',
           '\tpublic readonly record struct Run( int Capacity, Frame[] Frames );', '',
           '\tpublic static readonly Run[] Runs =', '\t[']
    for run in runs:
        cache = tc.Cache(run['capacity'])
        frames = []
        for frame in run['frames']:
            slots, builds = cache.resolve(frame['keys'], frame['dirty'])
            frames.append('new( %s, [%s], %s, %s, %s )' % (ints(frame['keys']), ', '.join('true' if d else 'false' for d in frame['dirty']), ints(slots),
                                                          ints(i for i, b in enumerate(builds) if b), ints(cache.ring())))
        out.append('\t\tnew( %d, [' % run['capacity'])
        out += ['\t\t\t' + frame + ',' for frame in frames]
        out.append('\t\t] ),')
    out += ['\t];', '}', '']
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
