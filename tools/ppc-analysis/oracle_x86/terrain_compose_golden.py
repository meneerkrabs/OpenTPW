"""Golden hashes of the composite tail of tp.exe's build routine 0x55f780 (floor descriptor given) on synthetic levels and art (docs/OBJECTS.md, "Floors", docs/reverse/ORACLE.md X33).

The levels are the 'C' mix levels of `terrain_synthetic_golden.py` (`terrain_reading.synthetic_level`) and the art comes from `terrain_reading.synthetic_art` (the same LCG); OpenTPW.Tests builds both
(`SyntheticTerrain`, `ObjectFloorBaseTests`) and checks `ProceduralTerrainTexturer.Compose` against these hashes without any game data, so CI covers the eight orientations (and the order in which the
word's bits are tested), the blend at every alpha extreme and art sizes that are, are not and are smaller than multiples of N. Prints C# source for `ProceduralTerrainComposeGolden.cs`.

Usage: OPENTPW_TPW_EXE=/path/tp.exe python3 -I terrain_compose_golden.py > source/OpenTPW.Tests/ProceduralTerrainComposeGolden.cs
Dev-only: needs Unicorn (pip install unicorn==2.1.4) and the identified tp.exe.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import terrain_reading as terrain  # noqa: E402
import x86_targets as targets  # noqa: E402
from x86_harness import UNICORN_HINT, Image, executable_path, have_unicorn  # noqa: E402


def main() -> int:
    if not have_unicorn():
        print(UNICORN_HINT, file=sys.stderr)
        return 2
    exe = executable_path('tpw')
    if exe is None:
        print('OPENTPW_TPW_EXE must name the identified tp.exe', file=sys.stderr)
        return 2
    target = targets.TERRAIN_COMPOSE_TARGET
    sandbox = target.sandbox(Image.load(exe))
    out = ['// Generated by tools/ppc-analysis/oracle_x86/terrain_compose_golden.py from tp.exe 0x55f780 run in the x86 oracle (docs/OBJECTS.md, "Floors").',
           '// Synthetic levels (SyntheticTerrain) and art (ObjectFloorBaseTests.SyntheticArt), not original data: hashes of the N x N x 4 bytes the original routine wrote with a floor descriptor.',
           'namespace OpenTPW.Tests;', '', 'internal static class ProceduralTerrainComposeGolden', '{',
           '\tpublic static readonly (int Seed, int Size, int X, int Z, string ArtSize, int ArtSeed, int Word, string Alpha, string Sha256)[] Cases =', '\t[']
    mismatches = 0
    for seed, n_size, x, z, kind, art_seed, word, alpha in terrain.compose_specs():
        level = terrain.synthetic_level(seed, 'C', n_size, False)
        width, height = terrain.compose_art_size(kind, n_size)
        pixels = terrain.synthetic_art(art_seed, width, height, alpha)
        case = {'n': n_size, 'x': x, 'z': z, 'level': level, 'art': {'pixels': pixels, 'width': width, 'height': height, 'bpp': 4, 'word': word}}
        original = targets.run_binary(target, sandbox, case)
        reading = targets.terrain_compose_plan(case)
        if original != reading:
            mismatches += 1
            print(f'MISMATCH seed {seed} N={n_size} cell ({x}, {z}) art {kind} word {word:#x} alpha {alpha}', file=sys.stderr)
        out.append(f'\t\t({seed}, {n_size}, {x}, {z}, "{kind}", {art_seed}, 0x{word:X}, "{alpha}", "{hashlib.sha256(original).hexdigest()}"),')
    out += ['\t];', '}', '']
    print('\n'.join(out))
    print(f'reading vs tp.exe: {mismatches} problems', file=sys.stderr)
    return 1 if mismatches else 0


if __name__ == '__main__':
    sys.exit(main())
