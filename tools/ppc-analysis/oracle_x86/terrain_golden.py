"""Golden hashes of procedural terrain textures from tp.exe's own build routine 0x55f780 (docs/LND.md, docs/reverse/ORACLE.md X27).

Reads `terrain.wad/base.lnd` of the four themes from a private Data tree, runs the original routine in the x86 oracle sandbox for a seeded sample
of cells per theme and texture size (plus the corner cells and some invalid ones), checks the Python reading (terrain_reading.py) against it, and
prints C# source for `ProceduralTerrainGolden.cs`: per theme the SHA-256 of the base.lnd file and, per cell, the SHA-256 of the N x N x 4 bytes
the routine wrote. Only hashes leave the tool; no original bytes and no images are written.

Usage: OPENTPW_TPW_EXE=/path/tp.exe python3 -I terrain_golden.py /path/to/Data [--seed S] [> source/OpenTPW.Tests/ProceduralTerrainGolden.cs]
Dev-only: needs Unicorn (pip install unicorn==2.1.4) and the identified tp.exe.
"""
from __future__ import annotations

import argparse
import hashlib
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / 'lanes' / 'formats'))

import corpus_check  # noqa: E402
import terrain_reading as terrain  # noqa: E402
import x86_targets as targets  # noqa: E402
from x86_harness import UNICORN_HINT, Image, executable_path, have_unicorn  # noqa: E402

THEMES = ('jungle', 'fantasy', 'hallow', 'space')
SAMPLE = {16: 30, 32: 16, 64: 8}   # random cells per theme and size (the research swept every cell at 16 and hundreds at 32 and 64)


def lnd_bytes(data: Path, theme: str) -> bytes:
    for name, member in corpus_check.wad_members(data / 'levels' / theme / 'terrain.wad'):
        if name.replace('\\', '/').rsplit('/', 1)[-1].lower() == 'base.lnd':
            return member
    raise SystemExit(f'{theme}: terrain.wad has no base.lnd')


def sample_cells(lnd: dict, n_size: int, rng: random.Random) -> list[tuple[int, int]]:
    cells_x, cells_y = (lnd['width'] - 1) >> 2, (lnd['height'] - 1) >> 2
    chosen = [(0, 0), (cells_x - 1, 0), (0, cells_y - 1), (cells_x - 1, cells_y - 1)]
    chosen += [(rng.randrange(cells_x), rng.randrange(cells_y)) for _ in range(SAMPLE[n_size])]
    invalid = []
    grid, width = lnd['grid'], lnd['width']
    for z in range(cells_y):
        for x in range(cells_x):
            q = ((4 * (cells_y - z - 1) + 1) * width + 4 * x + 1) * 4
            if (grid[q] & grid[q + 4] & grid[q + 4 * width] & grid[q + 4 * width + 4]) != 0xFF:
                invalid.append((x, z))
    chosen += [invalid[i] for i in sorted(rng.sample(range(len(invalid)), min(2, len(invalid))))]
    return list(dict.fromkeys(chosen))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('data', type=Path, help='the game Data directory (levels/<theme>/terrain.wad)')
    parser.add_argument('--seed', default='terrain-golden-v1')
    args = parser.parse_args(argv)
    if not have_unicorn():
        print(UNICORN_HINT, file=sys.stderr)
        return 2
    exe = executable_path('tpw')
    if exe is None:
        print('OPENTPW_TPW_EXE must name the identified tp.exe', file=sys.stderr)
        return 2
    target = targets.TERRAIN_BUILD_TARGET
    sandbox = target.sandbox(Image.load(exe))
    out = ['// Generated by tools/ppc-analysis/oracle_x86/terrain_golden.py from tp.exe 0x55f780 run in the x86 oracle (docs/LND.md). Hashes only.',
           'namespace OpenTPW.Tests;', '', 'internal static class ProceduralTerrainGolden', '{',
           '\t/// <summary>Per theme: the SHA-256 of base.lnd, then (N, cell x, cell z, SHA-256 of the N x N x 4 bytes the original routine wrote).</summary>',
           '\tpublic static readonly (string Theme, string FileSha256, (int Size, int X, int Z, string Sha256)[] Cells)[] Themes =', '\t[']
    mismatches = 0
    for theme in THEMES:
        raw = lnd_bytes(args.data, theme)
        lnd = terrain.parse_lnd(raw)
        out.append(f'\t\t("{theme}", "{hashlib.sha256(raw).hexdigest()}", [')
        modes_seen: dict[str, int] = {}
        for n_size in (16, 32, 64):
            level = terrain.level_for(lnd, n_size)
            rng = random.Random(f'{args.seed}:{theme}:{n_size}')
            for x, z in sample_cells(lnd, n_size, rng):
                original = targets.run_binary(target, sandbox, {'n': n_size, 'x': x, 'z': z, 'level': level})
                reading, modes = terrain.build(level, n_size, x, z)
                for mode in modes.values():
                    modes_seen[mode] = modes_seen.get(mode, 0) + 1
                if original != reading:
                    mismatches += 1
                    print(f'MISMATCH {theme} N={n_size} cell ({x}, {z})', file=sys.stderr)
                out.append(f'\t\t\t({n_size}, {x}, {z}, "{hashlib.sha256(original).hexdigest()}"),')
        out.append('\t\t]),')
        print(f'{theme}: run modes {dict(sorted(modes_seen.items()))}', file=sys.stderr)
    out += ['\t];', '}', '']
    print('\n'.join(out))
    print(f'reading vs tp.exe: {mismatches} mismatches', file=sys.stderr)
    return 1 if mismatches else 0


if __name__ == '__main__':
    sys.exit(main())
