"""Golden cases of the visible-cell spans of tp.exe's 0x56BB00 (docs/LND.md, "The visible cells").

The cameras come from `terrain_spans.random_scene` and `special_scenes` (a seeded generator and fixed values, not original data); `terrain_spans.spans` reproduces the
original's rows, columns and farthest corner distance for them (the x86 oracle target `terrain_spans` compares both on 400 and more cameras). OpenTPW.Tests runs the C# port on
the same cameras without any game data and checks the min and max row, the far distance bits and a hash of the 128 start and 128 end bytes.

Usage: python3 -I terrain_spans_golden.py > source/OpenTPW.Tests/TerrainVisibleSpansGolden.cs
Needs no Unicorn: the reading is pinned against the executable by test_x86_oracle.py when the identified tp.exe is available.
"""
from __future__ import annotations

import hashlib
import random
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import terrain_spans as ts  # noqa: E402


def literal(value: float) -> str:
    text = '%.9g' % value
    if 'e' not in text and '.' not in text:
        text += '.0'
    return text + 'f'


def main() -> int:
    scenes = ts.special_scenes()
    rng = random.Random(829)
    scenes += [ts.random_scene(rng) for _ in range(60)]
    out = ['// Generated by tools/ppc-analysis/oracle_x86/terrain_spans_golden.py from the reading of tp.exe 0x56BB00 that the x86 oracle pins (docs/LND.md).',
           '// Synthetic cameras, not original data: the span rows, the farthest corner distance (as bits) and a hash of the 128 start and 128 end bytes.',
           'namespace OpenTPW.Tests;', '', 'internal static class TerrainVisibleSpansGolden', '{',
           '\tpublic readonly record struct Case( float[] Camera, float[] Matrix, float Low, float High, float Fov, float Aspect, float MaxDistance, float[] Origin, int[] Cells, float[] Size,',
           '\t\tint MinRow, int MaxRow, uint FarBits, string Sha256 );', '',
           '\tpublic static readonly Case[] Cases =', '\t[']
    for scene in scenes:
        result = ts.spans(scene)
        packed = struct.pack('<128b128b', *result['start'], *result['end'])
        far_bits = struct.unpack('<I', struct.pack('<f', result['far']))[0]
        floats = lambda values: '[' + ', '.join(literal(v) for v in values) + ']'
        out.append('\t\tnew( %s, %s, %s, %s, %s, %s, %s, %s, [%d, %d], %s, %d, %d, 0x%08X, "%s" ),' % (
            floats(scene['camera']), floats(scene['matrix']), literal(scene['low']), literal(scene['high']), literal(scene['fov']), literal(scene['aspect']),
            literal(scene['max_distance']), floats(scene['origin']), scene['cells'][0], scene['cells'][1], floats(scene['size']),
            result['min'], result['max'], far_bits, hashlib.sha256(packed).hexdigest()))
    out += ['\t];', '}', '']
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
