"""Golden hashes of synthetic procedural terrain levels from tp.exe's build routine 0x55f780 (docs/LND.md, docs/reverse/ORACLE.md X27).

The levels come from `terrain_reading.synthetic_level` (an LCG and fixed formulas, not original data); OpenTPW.Tests builds the same levels
(`SyntheticTerrain`) and checks its texturer against these hashes without any game data, so CI covers the weight interpolation, general ramps, window
offsets, N = 64, every run mode and the grey fallback. Prints C# source for `ProceduralTerrainSyntheticGolden.cs`.

Usage: OPENTPW_TPW_EXE=/path/tp.exe python3 -I terrain_synthetic_golden.py > source/OpenTPW.Tests/ProceduralTerrainSyntheticGolden.cs
Dev-only: needs Unicorn (pip install unicorn==2.1.4) and the identified tp.exe.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import terrain_reading as terrain  # noqa: E402
import x86_targets as targets  # noqa: E402
from x86_harness import UNICORN_HINT, Image, executable_path, have_unicorn  # noqa: E402


def main() -> int:
    if not have_unicorn():
        print(UNICORN_HINT, file=sys.stderr)
        return 2
    exe = executable_path('tpw')
    if exe is None:
        print('OPENTPW_TPW_EXE must name the identified tp.exe', file=sys.stderr)
        return 2
    target = targets.TERRAIN_BUILD_TARGET
    sandbox = target.sandbox(Image.load(exe))
    out = ['// Generated by tools/ppc-analysis/oracle_x86/terrain_synthetic_golden.py from tp.exe 0x55f780 run in the x86 oracle (docs/LND.md).',
           '// Synthetic levels (SyntheticTerrain), not original data: hashes of the N x N x 4 bytes the original routine wrote.',
           'namespace OpenTPW.Tests;', '', 'internal static class ProceduralTerrainSyntheticGolden', '{',
           '\tpublic static readonly (int Seed, string Mix, int Size, bool Grey, int X, int Z, string Sha256)[] Cells =', '\t[']
    modes_seen: set[str] = set()
    mismatches = 0
    for seed, mix, n_size, grey in terrain.synthetic_specs():
        level = terrain.synthetic_level(seed, mix, n_size, grey)
        for x, z in terrain.synthetic_cells(seed, grey):
            original = targets.run_binary(target, sandbox, {'n': n_size, 'x': x, 'z': z, 'level': level})
            reading, modes = terrain.build(level, n_size, x, z)
            modes_seen.update(modes.values())
            if grey and (x, z) == (1, 1) and modes:
                print(f'seed {seed}: the grey cell is not invalid', file=sys.stderr)
                mismatches += 1
            if original != reading:
                mismatches += 1
                print(f'MISMATCH seed {seed} {mix} N={n_size} cell ({x}, {z})', file=sys.stderr)
            out.append(f'\t\t({seed}, "{mix}", {n_size}, {str(grey).lower()}, {x}, {z}, "{hashlib.sha256(original).hexdigest()}"),')
    out += ['\t];', '}', '']
    print('\n'.join(out))
    print(f'modes reached {sorted(modes_seen)}; reading vs tp.exe: {mismatches} problems', file=sys.stderr)
    return 1 if mismatches or modes_seen != set(terrain.MODES) else 0


if __name__ == '__main__':
    sys.exit(main())
