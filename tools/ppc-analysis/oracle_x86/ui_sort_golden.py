"""Golden cases of the UI draw sorts (docs/reverse/ORACLE.md, finding X70; UI-004): tp.exe's record sort 0x5829E0 and triangle sort 0x565490 on tied keys and on small random key sets.

Usage: python3 -I tools/ppc-analysis/oracle_x86/ui_sort_golden.py > source/OpenTPW.Tests/UiDepthSortGolden.cs   (needs Unicorn and OPENTPW_TPW_EXE; --check FILE compares)
"""
from __future__ import annotations

import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from ui_sort_oracle import UiSortOracle  # noqa: E402


def render() -> str:
    oracle = UiSortOracle()
    lines = ['// <auto-generated> tools/ppc-analysis/oracle_x86/ui_sort_golden.py: tp.exe 0x5829E0 and 0x565490 run in the x86 oracle (ORACLE.md X70). Do not edit. </auto-generated>',
             'namespace OpenTPW.Tests;', '', 'internal static class UiDepthSortGolden', '{',
             '\t/// <summary>Element order after the sort of n equal keys, n = 1..64 (record sort and triangle sort agree).</summary>',
             '\tpublic static readonly int[][] TieOrders =', '\t{']
    for count in range(1, 65):
        order = oracle.record_order([0.0] * count)
        assert order == oracle.triangle_order([0.0] * count)
        lines.append('\t\tnew[] { ' + ', '.join(map(str, order)) + ' },')
    lines += ['\t};', '', '\t/// <summary>Keys (float bit patterns) and the order the original leaves them in.</summary>',
              '\tpublic static readonly (uint[] Keys, int[] Order)[] Cases =', '\t{']
    rng = random.Random('ui-sort-x70')
    import struct
    for _ in range(60):
        count = rng.randint(2, 30)
        keys = [rng.choice([0.0, 0.0, 1.5, 2.5, 0.25, 0.1]) for _ in range(count)]
        order = oracle.record_order(keys)
        assert order == oracle.triangle_order(keys)
        bits = [struct.unpack('<I', struct.pack('<f', key))[0] for key in keys]
        lines.append('\t\t(new uint[] { ' + ', '.join(f'0x{b:08X}u' for b in bits) + ' }, new[] { ' + ', '.join(map(str, order)) + ' }),')
    lines += ['\t};', '', '\t/// <summary>Three screen points (x0, y0, x1, y1, x2, y2 as float bit patterns) and whether 0x581320 keeps the triangle (w = 1).</summary>',
              '\tpublic static readonly (uint[] Points, bool Clockwise)[] FaceTests =', '\t{']
    for case in range(120):
        if case % 3 == 0:
            pts = [(rng.uniform(-100, 2200), rng.uniform(-100, 1700)) for _ in range(3)]
        elif case % 3 == 1:
            pts = [(float(rng.randint(0, 12)), float(rng.randint(0, 12))) for _ in range(3)]
        else:
            base = rng.uniform(0, 2000)
            pts = [(base + k * 0.1, base * 0.5 + k * 0.05) for k in range(3)]
        flat = [value for point in pts for value in point]
        bits = [struct.unpack('<I', struct.pack('<f', value))[0] for value in flat]
        lines.append('\t\t(new uint[] { ' + ', '.join(f'0x{b:08X}u' for b in bits) + ' }, ' + ('true' if oracle.clockwise(pts) else 'false') + '),')
    lines += ['\t};', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = render()
    if len(sys.argv) == 3 and sys.argv[1] == '--check':
        sys.exit(0 if Path(sys.argv[2]).read_text() == text else 1)
    sys.stdout.write(text)
