"""Golden cases of tp.exe's wander destination 0x4F9490 (docs/reverse/ORACLE.md, finding X19; GUEST-010): the real routine on synthetic cells.

The oracle's own inputs (path, queue, entrance and exit cells with their link bytes and queue links; starts of every cell type that has links; scripted draws) are run through the routine in
the Unicorn sandbox and this script records its answer: the destination cell and sub-cell bytes with the number of draws it took, or none with the number of draws and whether the guest was
stranded. OpenTPW.Tests replays every row on GuestWander.Pick.

Usage: python3 -I tools/ppc-analysis/oracle_x86/wander_golden.py > source/OpenTPW.Tests/WanderGolden.cs   (needs Unicorn and OPENTPW_TPW_EXE)
"""
from __future__ import annotations

import base64
import sys
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from x86_differential import target_inputs  # noqa: E402
from x86_harness import Image, executable_path, have_unicorn  # noqa: E402
from x86_targets import TARGETS, run_binary  # noqa: E402

COUNT = 500
KEEP = 360


def render() -> str:
    target = next(t for t in TARGETS if t.key == 'tpw-exe-wander-destination')
    image = Image.load(executable_path('tpw'))
    inputs = target_inputs(target, COUNT, 'oracle-v1')
    sandbox = target.sandbox(image)
    # the edge cases, then an even share of the linked paths and of the any-start inputs
    chosen = inputs[:27] + inputs[27:27 + COUNT][::max(1, COUNT // 160)] + inputs[27 + COUNT:][::max(1, COUNT // 160)]
    lines = []
    for x in chosen[:KEEP]:
        original = run_binary(target, sandbox, x)
        cells = ';'.join(f'{cx},{cy},{kind},{links},{queue}' for cx, cy, kind, links, queue in x['cells'])
        draws = ','.join(str(d) for d in x['draws'][:14])
        if original[0] is None:
            answer = f'none {original[1]} {int(bool(original[2]))}'
        else:
            (cx, cy), bx, by, used = original
            answer = f'{cx} {cy} {bx} {by} {used}'
        lines.append(f'{x["start"][0]},{x["start"][1]} | {draws} | {cells} > {answer}')
    packed = base64.b64encode(zlib.compress('\n'.join(lines).encode(), 9)).decode()
    out = ['// Generated by tools/ppc-analysis/oracle_x86/wander_golden.py from tp.exe\'s own wander destination 0x4F9490 run in the x86 oracle (docs/reverse/ORACLE.md, X19; GUEST-010).',
           '// Synthetic cells, no original data. One row per line when unpacked, zlib-compressed and base64-coded: the start cell | the scripted draws | the cells as x,y,type,links,queue link separated by semicolons',
           '// > the routine\'s answer: the destination cell, its sub-cell bytes and the draws taken, or "none", the draws taken and 1 when the guest was stranded.',
           'namespace OpenTPW.Tests;', '', 'internal static class WanderGolden', '{',
           f'\t/// <summary>The oracle\'s {len(lines)} rows, packed.</summary>', '\tpublic const string Packed =']
    chunk = 120
    parts = [packed[i:i + chunk] for i in range(0, len(packed), chunk)]
    out += [f'\t\t"{part}"' + (' +' if i + 1 < len(parts) else ';') for i, part in enumerate(parts)]
    out += ['', f'\tpublic const int RowCount = {len(lines)};', '}', '']
    return '\n'.join(out)


def main() -> int:
    if not have_unicorn():
        print('needs Unicorn and OPENTPW_TPW_EXE', file=sys.stderr)
        return 2
    if len(sys.argv) == 3 and sys.argv[1] == '--check':
        if render() != Path(sys.argv[2]).read_text():
            print('WanderGolden.cs differs from the oracle output', file=sys.stderr)
            return 1
        return 0
    print(render(), end='')
    return 0


if __name__ == '__main__':
    sys.exit(main())
