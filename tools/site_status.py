"""Generate the website's live status page and data from the repository (standard library only).

Usage: python3 -I tools/site_status.py [--repo CHECKOUT] [--pulls-json FILE] [--write-front] [--no-front-check]

Reads docs/FIDELITY-REGISTER.md, docs/reverse/ORACLE.md, docs/FEATURE-MATRIX.md, the README format table,
the merged pull requests and the checked-out commit, and writes website/docs/status.json and
website/docs/status.html (ignored build output, like the rest of website/docs). The front page's
"You can / You cannot yet" block comes from tools/site_status_curated.json: it is committed in
website/index.html between the site-status markers; without --no-front-check the build fails when it
is out of date and --write-front rewrites it. Merged pull requests come from --pulls-json (the output
of `gh api repos/OWNER/REPO/pulls?state=closed`), otherwise from `git log --first-parent`. The output
depends only on the repository, that file and the commit, so it is reproducible.

Oracle figures: findings are the bold "**F<n>, title**" paragraphs and "Finding X<n>" headings of
docs/reverse/ORACLE.md. C# agreement is counted per section 4 target, not per finding: a target counts
as "agree" when its "vs C# on main" cell reports **agree** without an "except" clause (see csharp_status).
"""

from __future__ import annotations

import argparse
import html
import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

REPO_URL = "https://github.com/meneerkrabs/OpenTPW"
RECENT = 10
BEGIN = "<!-- site-status:begin (generated by tools/site_status.py from tools/site_status_curated.json; do not edit) -->"
END = "<!-- site-status:end -->"


def plain(text: str) -> str:
    """Markdown cell to plain text: links keep their label, emphasis and code marks go."""
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return re.sub(r"[`*]", "", text).strip()


def table_rows(lines: list[str], header_start: str) -> list[list[str]]:
    """Cells of the first pipe table whose header row starts with header_start."""
    for i, line in enumerate(lines):
        if line.startswith(header_start):
            rows = []
            for row in lines[i + 2:]:
                if not row.startswith("|"):
                    break
                rows.append([c.strip() for c in re.split(r"(?<!\\)\|", row.strip())[1:-1]])
            return rows
    return []


def parse_register(text: str) -> dict:
    total = re.search(r"\*\*(\d+) unresolved unique APPROX IDs\*\*", text)
    split = re.search(r"(\d+) IDs belong to the existing original-fidelity areas.*?and (\d+) ONLINE IDs", text, re.S)
    areas = [{"area": r[0], "ids": int(r[1]), "occurrences": int(r[2])}
             for r in table_rows(text.splitlines(), "| Area | Unique unresolved IDs") if len(r) == 3]
    if not total or not split or not areas:
        raise ValueError("docs/FIDELITY-REGISTER.md: header counts or area table not found")
    return {"total": int(total.group(1)), "original": int(split.group(1)), "online": int(split.group(2)), "areas": areas}


def csharp_status(cell: str) -> str:
    """Classify the "vs C# on main" cell of an ORACLE.md section 4 target row.

    agree: the cell reports **agree** for the C# port (the whole target matches the original routine);
    partial: **agree** except for named inputs; no-port: no C# hook or port exists yet; differs: C# is
    compared and still differs from the original."""
    text = cell.lower()
    if "**agree**" in text:
        return "partial" if " except " in text else "agree"
    if re.search(r"\bno (c# )?(hook|port)\b|not on main|^hook\b", text):
        return "no-port"
    return "differs"


def parse_oracle(text: str) -> dict:
    found: dict[str, str] = {}
    for line in text.splitlines():
        m = re.match(r"\*\*([FX]\d+),\s*([^*]*?)\*\*", line) or re.match(r"#{2,4}\s+[\d.a-z]*\s*Finding ([FX]\d+):\s*(.+)$", line)
        if m and m.group(1) not in found:
            title = plain(re.split(r"\s+\(|[:;]", m.group(2).strip().rstrip("."))[0]).rstrip(".")
            found[m.group(1)] = title
    items = [{"id": k, "title": v} for k, v in sorted(found.items(), key=lambda kv: (kv[0][0], int(kv[0][1:])))]
    section = re.search(r"^## 4\..*?(?=^## )", text, re.S | re.M)
    targets = []
    for row in table_rows(section.group(0).splitlines() if section else [], "| Target | Routine"):
        if len(row) == 6:
            targets.append({"target": plain(row[0]), "csharp": csharp_status(row[5])})
    counts = {k: sum(t["csharp"] == k for t in targets) for k in ("agree", "partial", "differs", "no-port")}
    return {"findings": items,
            "f_count": sum(i["id"][0] == "F" for i in items),
            "x_count": sum(i["id"][0] == "X" for i in items),
            "targets": targets, "target_count": len(targets), "csharp_agrees": counts["agree"], "csharp": counts}


MATRIX_COLUMNS = ["area", "gate", "implementation", "macos", "windows", "linux", "original_vm", "evidence"]


def parse_matrix(text: str) -> dict:
    rows = [dict(zip(MATRIX_COLUMNS, (plain(c) for c in r)))
            for r in table_rows(text.splitlines(), "| Required area | Gate | Implementation") if len(r) == len(MATRIX_COLUMNS)]
    if not rows:
        raise ValueError("docs/FEATURE-MATRIX.md: coverage table not found")
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["implementation"]] = counts.get(r["implementation"], 0) + 1
    return {"rows": rows, "counts": dict(sorted(counts.items()))}


def parse_formats(text: str) -> dict:
    lines = text.splitlines()
    rows = [{"format": plain(re.sub(r"\s*\(.*$", "", r[0])), "status": "decoded" if "✅" in r[1] else "partial",
             "note": plain(r[2]), "open": plain(r[3]), "game": plain(r[4])}
            for r in table_rows(lines, "| Format | Decoding") if len(r) == 5]
    if not rows:
        raise ValueError("README.md: file format table not found")
    return {"rows": rows, "decoded": sum(r["status"] == "decoded" for r in rows), "partial": sum(r["status"] == "partial" for r in rows)}


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True).stdout.strip()


def commit_info(repo: Path) -> dict:
    try:
        sha, date = git(repo, "log", "-1", "--format=%H|%cI").split("|")
        return {"sha": sha, "short": sha[:8], "date": date}
    except (subprocess.CalledProcessError, FileNotFoundError, ValueError):
        return {"sha": "", "short": "unknown", "date": ""}


def pulls_from_api(data: list[dict], limit: int = RECENT) -> list[dict]:
    merged = [p for p in data if p.get("merged_at")]
    merged.sort(key=lambda p: (p["merged_at"], p["number"]), reverse=True)
    return [{"number": p["number"], "title": p["title"], "date": p["merged_at"][:10], "url": p["html_url"]} for p in merged[:limit]]


def pulls_from_git(repo: Path, limit: int = RECENT) -> list[dict]:
    try:
        out = git(repo, "log", "--first-parent", f"-{limit}", "--format=%H%x1f%cI%x1f%s")
    except (subprocess.CalledProcessError, FileNotFoundError):
        return []
    items = []
    for line in out.splitlines():
        sha, date, subject = line.split("\x1f")
        number = re.search(r"\(#(\d+)\)\s*$", subject) or re.match(r"Merge pull request #(\d+)", subject)
        items.append({"number": int(number.group(1)) if number else None,
                      "title": re.sub(r"\s*\(#\d+\)\s*$", "", subject), "date": date[:10],
                      "url": f"{REPO_URL}/pull/{number.group(1)}" if number else f"{REPO_URL}/commit/{sha}"})
    return items


def recent(repo: Path, pulls_json: Path | None) -> dict:
    if pulls_json and pulls_json.is_file():
        try:
            data = json.loads(pulls_json.read_text(encoding="utf-8"))
            items = pulls_from_api(data) if isinstance(data, list) else []
            if items:
                return {"source": "github", "items": items}
        except (ValueError, KeyError, TypeError):
            pass
    return {"source": "git", "items": pulls_from_git(repo)}


def load_curated(repo: Path, matrix: dict) -> dict:
    """The curated lists; raises ValueError for anything that no longer matches the repository."""
    data = json.loads((repo / "tools" / "site_status_curated.json").read_text(encoding="utf-8"))
    areas = {r["area"] for r in matrix["rows"]}
    problems = []
    for key in ("can", "cannot"):
        for item in data.get(key, []):
            for area in item.get("matrix", []):
                if area not in areas:
                    problems.append(f"{key}: unknown FEATURE-MATRIX area {area!r}")
            href = item.get("href")
            if href and not doc_exists(repo, href):
                problems.append(f"{key}: no source document for {href}")
    if data.get("later_href") and not doc_exists(repo, data["later_href"]):
        problems.append(f"later: no source document for {data['later_href']}")
    if not data.get("can") or not data.get("cannot") or not data.get("later"):
        problems.append("can, cannot and later are required")
    if problems:
        raise ValueError("tools/site_status_curated.json: " + "; ".join(problems))
    return data


def doc_exists(repo: Path, href: str) -> bool:
    return href.startswith("docs/") and href.endswith(".html") and (repo / (href[:-5] + ".md")).is_file()


def collect(repo: Path, pulls_json: Path | None = None) -> dict:
    read = lambda name: (repo / name).read_text(encoding="utf-8")
    matrix = parse_matrix(read("docs/FEATURE-MATRIX.md"))
    return {"commit": commit_info(repo),
            "fidelity": parse_register(read("docs/FIDELITY-REGISTER.md")),
            "oracle": parse_oracle(read("docs/reverse/ORACLE.md")),
            "features": matrix,
            "formats": parse_formats(read("README.md")),
            "recent": recent(repo, pulls_json),
            "curated": load_curated(repo, matrix)}


# ---- Rendering --------------------------------------------------------------------------------------------

def esc(text: str) -> str:
    return html.escape(str(text), quote=True)


def li(item: dict, prefix: str = "") -> str:
    """List item; hrefs are site-root relative ("docs/X.html"), and prefix "docs/" is stripped for pages inside docs/."""
    link = f' <a href="{esc(item["href"].removeprefix(prefix))}">Details</a>' if item.get("href") else ""
    return f"<li>{esc(item['text'])}{link}</li>"


def front_block(curated: dict) -> str:
    """The committed front-page block (curated only, so it changes only when the curated file does)."""
    can = "\n".join("\t\t\t\t\t" + li(i, "") for i in curated["can"])
    cannot = "\n".join("\t\t\t\t\t" + li(i, "") for i in curated["cannot"])
    later = esc(curated["later"]) + (f' <a href="{esc(curated["later_href"])}">Details</a>' if curated.get("later_href") else "")
    return f"""{BEGIN}
		<div class="status-grid">
			<div class="status-card works">
				<h3>You can</h3>
				<ul>
{can}
				</ul>
			</div>
			<div class="status-card todo">
				<h3>You cannot yet</h3>
				<ul>
{cannot}
				</ul>
			</div>
		</div>
		<p class="note-later"><strong>Later:</strong> {later}</p>
		{END}"""


BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)


def front_current(repo: Path, curated: dict) -> tuple[bool, str]:
    path = repo / "website" / "index.html"
    source = path.read_text(encoding="utf-8")
    if not BLOCK.search(source):
        raise ValueError("website/index.html: site-status markers not found")
    updated = BLOCK.sub(lambda _: front_block(curated), source, count=1)
    return updated == source, updated


def stat(value: object, label: str, note: str) -> str:
    return f'<div class="stat"><span class="stat-num">{esc(value)}</span><span class="stat-label">{esc(label)}</span><span class="stat-note">{esc(note)}</span></div>'


def recent_list(recent_data: dict, limit: int) -> str:
    items = recent_data["items"][:limit]
    if not items:
        return "<p>No merged changes could be read.</p>"
    rows = "".join(f'<li><a href="{esc(i["url"])}">{esc(i["title"])}</a> <span class="doc-file">{"#" + str(i["number"]) + " · " if i["number"] else ""}{esc(i["date"])}</span></li>' for i in items)
    return f"<ul class=\"doc-list\">{rows}</ul>"


def table(headers: list[str], rows: list[list[str]]) -> str:
    head = "".join(f"<th>{esc(h)}</th>" for h in headers)
    body = "".join("<tr>" + "".join(f"<td>{esc(c)}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="table-wrap"><table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>'


def stamp(status: dict) -> str:
    c = status["commit"]
    link = f'<a href="{REPO_URL}/commit/{esc(c["sha"])}"><code>{esc(c["short"])}</code></a>' if c["sha"] else "<code>unknown</code>"
    return f"Generated from commit {link} on {esc(c['date'][:10] or 'an unknown date')}"


def render_page(status: dict) -> str:
    f, o, m, fm, r, cur = (status[k] for k in ("fidelity", "oracle", "features", "formats", "recent", "curated"))
    source = "the GitHub API (merged pull requests)" if r["source"] == "github" else "the first-parent history of the checked-out branch"
    tiles = "".join([
        stat(f["total"], "open fidelity items", f"{f['original']} in the original areas, {f['online']} online"),
        stat(o["f_count"] + o["x_count"], "executed oracle findings", f"{o['f_count']} F, {o['x_count']} X; C# agrees with the original in {o['csharp_agrees']} of {o['target_count']} executed targets"),
        stat(fm["decoded"], "formats fully decoded", f"{fm['partial']} more partly"),
        stat(len(m["rows"]), "feature areas tracked", ", ".join(f"{n} {k}" for k, n in m["counts"].items())),
    ])
    areas = table(["Area", "Open IDs", "Source occurrences"], [[a["area"], a["ids"], a["occurrences"]] for a in f["areas"]])
    findings = table(["Finding", "Title"], [[i["id"], i["title"]] for i in o["findings"]])
    labels = {"agree": "agrees", "partial": "agrees except named inputs", "differs": "differs", "no-port": "no C# port or hook yet"}
    targets = table(["Executed target", "C# on main"], [[t["target"], labels[t["csharp"]]] for t in o["targets"]])
    matrix = table(["Area", "Gate", "Implementation", "macOS", "Windows", "Linux", "Original VM"],
                   [[x["area"], x["gate"], x["implementation"], x["macos"], x["windows"], x["linux"], x["original_vm"]] for x in m["rows"]])
    formats = table(["Format", "Decoding", "Still open in the format"], [[x["format"], x["status"], x["open"][:160] + ("..." if len(x["open"]) > 160 else "")] for x in fm["rows"]])
    body = f"""<h1>Project status</h1>
<p class="lead">Figures read from the repository when this site was built, so they match what is merged on <code>main</code>. {stamp(status)}.</p>
<div class="stats">{tiles}</div>
<h2 id="can">You can, you cannot yet</h2>
<div class="status-grid"><div class="status-card works"><h3>You can</h3><ul>{"".join(li(i, "docs/") for i in cur["can"])}</ul></div>
<div class="status-card todo"><h3>You cannot yet</h3><ul>{"".join(li(i, "docs/") for i in cur["cannot"])}</ul></div></div>
<p><strong>Later:</strong> {esc(cur["later"])}</p>
<h2 id="progress">Recent progress</h2>
<p>The latest merged changes, from {source}.</p>
{recent_list(r, RECENT)}
<h2 id="fidelity">Open fidelity items</h2>
<p>{f["total"]} unresolved APPROX IDs: {f["original"]} in the original-fidelity areas and {f["online"]} inside the online extension. Source: <a href="FIDELITY-REGISTER.html">fidelity register</a>, generated from tagged code sites.</p>
{areas}
<h2 id="oracle">Executed oracle findings</h2>
<p>Rules traced in the original binaries and executed against OpenTPW: {o["f_count"]} Mac PowerPC findings (F) and {o["x_count"]} cross-binary findings (X). Source: <a href="reverse/ORACLE.html">oracle notes</a>.</p>
{findings}
<p>Targets where C# agrees with the original: <strong>{o["csharp_agrees"]} of {o["target_count"]}</strong> ({o["csharp"]["partial"]} more agree except for named inputs, {o["csharp"]["differs"]} differ, {o["csharp"]["no-port"]} have no C# port or hook yet). A target is one routine of the original run against the C# code, from the target table of the oracle notes.</p>
{targets}
<h2 id="features">Feature status by area</h2>
<p>Source: <a href="FEATURE-MATRIX.html">feature matrix</a>. Implemented or self-tested does not mean original fidelity; unassessed means no evidence yet either way.</p>
{matrix}
<h2 id="formats">File formats</h2>
<p>Source: the format table in the <a href="README.html#file-formats">README</a>. Decoded means every observed file decodes and its fields are understood; partial means some bytes or field meanings are still unknown. Game integration is listed separately in the README.</p>
{formats}"""
    return load_site_docs().page("Project status", body, 0, "tools/site_status.py")


def load_site_docs():
    spec = importlib.util.spec_from_file_location("site_docs", Path(__file__).with_name("site_docs.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def write_outputs(repo: Path, status: dict) -> Path:
    out = repo / "website" / "docs"
    out.mkdir(parents=True, exist_ok=True)
    data = {k: v for k, v in status.items() if k != "curated"}
    data["curated"] = {"can": status["curated"]["can"], "cannot": status["curated"]["cannot"], "later": status["curated"]["later"]}
    (out / "status.json").write_text(json.dumps(data, indent=1, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
    (out / "status.html").write_text(render_page(status), encoding="utf-8")
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--pulls-json", type=Path, default=None, help="output of the GitHub pulls API; falls back to git history")
    parser.add_argument("--write-front", action="store_true", help="rewrite the front page's curated block")
    parser.add_argument("--no-front-check", action="store_true", help="skip the front page freshness check")
    args = parser.parse_args()
    repo = args.repo.resolve()
    try:
        status = collect(repo, args.pulls_json)
        current, updated = front_current(repo, status["curated"])
    except (ValueError, OSError) as error:
        print(f"site_status: {error}", file=sys.stderr)
        return 1
    if args.write_front and not current:
        (repo / "website" / "index.html").write_text(updated, encoding="utf-8")
        current = True
        print("site_status: rewrote the front page block")
    out = write_outputs(repo, status)
    print(f"site_status: wrote status.html and status.json to {out.relative_to(repo)} "
          f"({status['fidelity']['total']} open items, {len(status['oracle']['findings'])} findings, "
          f"{len(status['recent']['items'])} recent changes from {status['recent']['source']})")
    if not current and not args.no_front_check:
        print("site_status: website/index.html is out of date; run python3 tools/site_status.py --write-front", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
